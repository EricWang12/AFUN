from __future__ import annotations

import json
import pathlib
from dataclasses import dataclass
from typing import Any, Dict, List

import numpy as np
import torch
from PIL import Image

from .base import DatasetBase

from src.data.sam3_utils import collate_to_sam3


# ----------------------------- IO helpers -----------------------------

def _imread_rgb(path: str) -> np.ndarray:
    with Image.open(path) as img:
        return np.array(img.convert("RGB"))


def _imread_gray(path: str) -> np.ndarray:
    with Image.open(path) as img:
        return np.array(img.convert("L"))


def _resize_mask_nearest(mask: np.ndarray, *, out_h: int, out_w: int) -> np.ndarray:
    if mask.shape[0] == out_h and mask.shape[1] == out_w:
        return mask
    m = torch.from_numpy(mask).float()[None, None]
    m2 = torch.nn.functional.interpolate(m, size=(out_h, out_w), mode="nearest")
    return m2[0, 0].cpu().numpy()


# ----------------------------- sample record -----------------------------

@dataclass(frozen=True)
class _HOVASample:
    image_path: str
    mask_path: str
    query: str
    source: str


# ----------------------------- dataset -----------------------------

class HOVA500KDataset(DatasetBase):
    """Read masks and instructions generated by scripts/prepare_hova.py."""

    def __init__(
        self,
        data_dir: str | pathlib.Path,
        *,
        split: str = "train",
        index_file: str = "mask_annotation/dataset_index.json",
        dtype: torch.dtype = torch.float32,
        transform=None,
        binarize_mask: bool = True,
        mask_threshold: float = 0.5,
        loader_cfg: Dict[str, Any] = None,
        **kwargs: Any,
    ):
        if isinstance(data_dir, str):
            data_dir = pathlib.Path(data_dir)
        super().__init__(data_dir=data_dir, split=split, dtype=dtype)

        self.transform = transform
        self.binarize_mask = binarize_mask
        self.mask_threshold = mask_threshold
        self.loader_cfg = loader_cfg

        self.meta: List[_HOVASample] = []
        self._load_index(data_dir / index_file)

    def _load_index(self, path: pathlib.Path) -> None:
        if not path.exists():
            raise FileNotFoundError(
                f"[HOVA500KDataset] Index not found: {path}\n"
                "  Generate it with scripts/prepare_hova.py (see the README's Training section)."
            )
        with open(path) as f:
            records = json.load(f)

        total = 0
        for r in records:
            total += 1
            if r.get("split", "train") != self.split:
                continue
            self.meta.append(_HOVASample(
                image_path=str(self._resolve_path(r["image_path"])),
                mask_path=str(self._resolve_path(r["mask_path"])),
                query=r["query"],
                source=r["source"],
            ))
        print(f"[HOVA500KDataset] split={self.split}: {len(self.meta)}/{total} samples from {path.name}")

    def _resolve_path(self, value):
        path = pathlib.Path(value)
        if path.is_absolute():
            # Older indices stored the machine's HOVA-500K root.
            if "HOVA-500K" in path.parts:
                path = pathlib.Path(*path.parts[path.parts.index("HOVA-500K") + 1:])
            elif path.exists():
                return path
        return self.data_dir / path

    def __len__(self) -> int:
        return len(self.meta)

    def set_progress(self, global_step: int) -> None:
        self._global_step = global_step

    # ---------------------- item loading ----------------------

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        s = self.meta[idx]

        img = _imread_rgb(s.image_path).astype(np.float32) / 255.0
        mask = _imread_gray(s.mask_path).astype(np.float32) / 255.0

        if self.transform is not None:
            img = self.transform(img)

        H, W = img.shape[:2]
        if mask.shape[0] != H or mask.shape[1] != W:
            mask = _resize_mask_nearest(mask, out_h=H, out_w=W)

        if self.binarize_mask:
            mask = (mask > self.mask_threshold).astype(np.float32)

        img_t = torch.as_tensor(img, dtype=self.dtype).permute(2, 0, 1).contiguous()
        mask_t = torch.as_tensor(mask, dtype=self.dtype).unsqueeze(0).contiguous()

        return {
            "image": img_t,         # (3, H, W)
            "mask": mask_t,          # (1, H, W)
            "query": [s.query],      # List[str]
            "source": s.source,
            "split": self.split,
        }

    # ---------------------- dataloader glue ----------------------

    @staticmethod
    def collate_function(batch: List[Dict[str, Any]], **kwargs) -> Dict[str, Any]:
        return collate_to_sam3(batch, **kwargs)

    # Uses base class build_dataloader which reads all loader_cfg params
    # including persistent_workers, prefetch_factor, multiprocessing_context
